#!/usr/bin/env python3
"""Generates native/include/render360_core_exports.h: C declarations of every
extern "C" r360_* function the Render360 bootstrap core defines (the same
surface the browser build exports to JavaScript). Run after changing exports:
    python3 native/tools/gen_core_api.py
"""
import pathlib, re, sys
ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "src" / "xenia_web_bootstrap"
TYPES = r"(?:const\s+)?(?:void|bool|double|float|int|int32_t|uint8_t|uint16_t|uint32_t|uint64_t|int64_t|size_t|uintptr_t|char)\s*\**"
DEF = re.compile(r"^(?:extern\s+\"C\"\s+)?(?:__attribute__\(\([^;{]*?\)\)\s*)?(?:R360_WASM_EXPORT\([^)]*\)\s*)?(?:static\s+)?(?P<ret>" + TYPES + r")\s*(?P<name>r360_[A-Za-z0-9_]+)\s*\((?P<args>[^)]*)\)\s*(?:noexcept\s*)?\{", re.M)
SKIP_FILES = {"hir_wasm_jit.cpp"}
found = {}
# Overlay-generated units (prepare-*.py) replace some sources at build time.
OVERLAY = ROOT / "build" / "xenia-web-overlay" / "render360"
paths = sorted(SRC.glob("*.cpp")) + sorted(SRC.glob("*.inc"))
if OVERLAY.is_dir():
    paths = sorted(OVERLAY.glob("*.cpp")) + paths
for path in paths:
    if path.name in SKIP_FILES:
        continue
    text = path.read_text(errors="replace")
    # Join attribute lines with the definition that follows them.
    text = re.sub(r"(extern\s+\"C\"\s*)\n", r"\1 ", text)
    text = re.sub(r"(__attribute__\(\([^\n]*\)\)|R360_WASM_EXPORT\([^)]*\))\s*\n", r"\1 ", text)
    for m in DEF.finditer(text):
        name = m.group("name")
        args = " ".join(m.group("args").split())
        ret = " ".join(m.group("ret").split())
        found.setdefault(name, (ret, args, path.name))
out = ["// Generated by native/tools/gen_core_api.py - do not edit.",
       "// Every r360_* entry point of the Render360 core (browser: wasm exports).",
       "#pragma once", "#include <stdbool.h>", "#include <stddef.h>", "#include <stdint.h>",
       "#ifdef __cplusplus", 'extern "C" {', "#endif"]
for name in sorted(found):
    ret, args, src = found[name]
    out.append(f"{ret} {name}({args or 'void'});  // {src}")
out += ["#ifdef __cplusplus", "}", "#endif", ""]
dest = ROOT / "native" / "include" / "render360_core_exports.h"
dest.write_text("\n".join(out))
print(f"{len(found)} r360_* functions -> {dest.relative_to(ROOT)}", file=sys.stderr)
